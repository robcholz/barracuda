/// An ES8389 at a caller-selected seven-bit I2C address.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Es8389 {
    address: u8,
}

impl Es8389 {
    /// Creates a driver when `address` is a valid seven-bit I2C address.
    #[must_use]
    pub const fn new(address: u8) -> Option<Self> {
        if address <= 0x7f {
            Some(Self { address })
        } else {
            None
        }
    }

    /// Programs 16-kHz stereo operation and optionally derives MCLK from BCLK.
    pub fn initialize<I2C: I2c, DELAY: DelayNs>(
        &self,
        i2c: &mut I2C,
        derive_clock_from_bclk: bool,
        delay: &mut DELAY,
    ) -> Result<(), I2C::Error> {
        self.write_sequence(i2c, INITIAL_REGISTERS)?;
        delay.delay_ms(10);
        if derive_clock_from_bclk {
            self.write_register(i2c, 0x02, 0x40)?;
            self.write_sequence(i2c, BCLK_16_KHZ_REGISTERS)?;
        }
        self.write_sequence(i2c, BIAS_ON_REGISTERS)
    }

    /// Writes both DAC volume registers.
    pub fn set_dac_volume<I2C: I2c>(&self, i2c: &mut I2C, volume: u8) -> Result<(), I2C::Error> {
        self.write_register(i2c, 0x46, volume)?;
        self.write_register(i2c, 0x47, volume)
    }

    fn write_sequence<I2C: I2c>(
        &self,
        i2c: &mut I2C,
        sequence: &[(u8, u8)],
    ) -> Result<(), I2C::Error> {
        for &(register, value) in sequence {
            self.write_register(i2c, register, value)?;
        }
        Ok(())
    }

    fn write_register<I2C: I2c>(
        &self,
        i2c: &mut I2C,
        register: u8,
        value: u8,
    ) -> Result<(), I2C::Error> {
        i2c.write(self.address, &[register, value])
    }
}
