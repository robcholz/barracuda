/// Product and version registers read from the sensor bank.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Identity {
    /// Product identifier.
    pub product: u8,
    /// Product version.
    pub version: u8,
}

impl Identity {
    /// Returns whether this is the expected OV2640 `0x26/0x42` identity.
    #[must_use]
    pub const fn is_ov2640(self) -> bool {
        self.product == 0x26 && self.version == 0x42
    }
}

/// An OV2640 at a caller-selected seven-bit SCCB address.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Ov2640 {
    address: u8,
}

impl Ov2640 {
    /// Creates a driver when `address` is a valid seven-bit SCCB address.
    #[must_use]
    pub const fn new(address: u8) -> Option<Self> {
        if address <= 0x7f {
            Some(Self { address })
        } else {
            None
        }
    }

    /// Selects the sensor bank and reads the product identity.
    pub fn identity<I2C: I2c>(&self, i2c: &mut I2C) -> Result<Identity, I2C::Error> {
        self.write_register(i2c, 0xff, 0x01)?;
        Ok(Identity {
            product: self.read_register(i2c, 0x0a)?,
            version: self.read_register(i2c, 0x0b)?,
        })
    }

    /// Programs QVGA JPEG output.
    pub fn initialize_qvga_jpeg<I2C: I2c, DELAY: DelayNs>(
        &self,
        i2c: &mut I2C,
        delay: &mut DELAY,
    ) -> Result<(), I2C::Error> {
        self.write_register(i2c, 0x12, 0x80)?;
        delay.delay_ms(10);
        for &(register, value) in QVGA_JPEG_REGISTERS {
            self.write_register(i2c, register, value)?;
        }
        delay.delay_ms(10);
        Ok(())
    }

    fn write_register<I2C: I2c>(
        &self,
        i2c: &mut I2C,
        register: u8,
        value: u8,
    ) -> Result<(), I2C::Error> {
        i2c.write(self.address, &[register, value])
    }

    fn read_register<I2C: I2c>(&self, i2c: &mut I2C, register: u8) -> Result<u8, I2C::Error> {
        let mut value = [0];
        i2c.write_read(self.address, &[register], &mut value)?;
        Ok(value[0])
    }
}
