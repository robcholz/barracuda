import { readdir } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "../..");
/** The counts the website quotes, generated from the repository. */
export const REPO_TS = resolve(ROOT, "website/src/content/repo.ts");

type PluginManifest = { id: string; "depends-on"?: string[] };

async function directories(path: string): Promise<string[]> {
  return (await readdir(resolve(ROOT, path), { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

async function present(path: string): Promise<boolean> {
  return Bun.file(resolve(ROOT, path)).exists();
}

/** How many Platforms, Plugins, and chat channels the repository holds. */
export async function repoCounts(): Promise<{
  platforms: number;
  plugins: number;
  channels: number;
}> {
  let platforms = 0;
  for (const name of await directories("platforms"))
    if (await present(`platforms/${name}/platform.yml`)) platforms += 1;
  const manifests: PluginManifest[] = [];
  for (const name of await directories("plugins")) {
    const path = resolve(ROOT, `plugins/${name}/plugin.toml`);
    if (await Bun.file(path).exists())
      manifests.push(
        Bun.TOML.parse(await Bun.file(path).text()) as PluginManifest,
      );
  }
  // A channel is an `imessage-*` Plugin that plugs into the Gateway.
  const channels = manifests.filter(
    (manifest) =>
      manifest.id.startsWith("imessage-") &&
      (manifest["depends-on"] ?? []).includes("imessage-gateway"),
  ).length;
  return { platforms, plugins: manifests.length, channels };
}

/** `website/src/content/repo.ts` for these counts. */
export function renderRepo(counts: {
  platforms: number;
  plugins: number;
  channels: number;
}): string {
  return [
    "// Generated by `bun tools/web/website-repo.ts` from the repository; do not",
    "// edit. `tools/web/website-repo.test.ts` fails while it is out of date.",
    "",
    "/** Platforms: the folders under `platforms/` with a `platform.yml`. */",
    `export const PLATFORMS = ${counts.platforms};`,
    "/** Plugins: the folders under `plugins/` with a `plugin.toml`. */",
    `export const PLUGINS = ${counts.plugins};`,
    "/** Ways to chat: the Plugins that add an iMessage Gateway channel. */",
    `export const CHANNELS = ${counts.channels};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  await Bun.write(REPO_TS, renderRepo(await repoCounts()));
}
